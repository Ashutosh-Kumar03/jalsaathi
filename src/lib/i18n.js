  // t('key', {var: value})
  export function makeT(lang) {
    return (key, vars) => {
      let s = (S[lang] && S[lang][key]) || S.en[key] || key;
      if (vars) {
        for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
      }
      return s;
    };
  }
  
  // engine ka stage (en naam) -> translation key
  export function stageKey(stageEn) {
    if (stageEn === 'Initial') return 'stage_Initial';
    if (stageEn === 'Development') return 'stage_Development';
    if (stageEn.startsWith('Mid')) return 'stage_Mid';
    return 'stage_Late';
  }